import { test, expect } from '@playwright/test';

test('walkthrough stays in the network and waits for actual choices', async ({ page }) => {
  await page.goto('/network');
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.getByRole('button', { name: /Take the journey|Follow one device|Start walkthrough/ }).click();
  const guide = page.getByRole('region', { name: 'One-device walkthrough' });
  await expect(guide).toBeVisible();
  await expect(page).toHaveURL(/\/network/);
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeDisabled();
  await guide.getByRole('button', { name: 'Submit sample request', exact: true }).click();
  await expect(guide.getByText('Sample request submitted')).toBeVisible();
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await expect(guide.getByRole('heading', { name: 'One request, one coordinated batch.' })).toBeVisible();
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeDisabled();
  await guide.getByRole('button', { name: 'Review and choose', exact: true }).click();
  await page.getByRole('button', { name: 'Review from checkpoint', exact: true }).click();
  await page.getByRole('button', { name: 'Retain hold', exact: true }).click();
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await expect(page).toHaveURL(/\/network\?mode=hub/);
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await expect(page).toHaveURL(/\/network\?asset=JB-A036/);
  await guide.getByRole('button', { name: 'Review and choose', exact: true }).click();
  await page.getByRole('button', { name: 'Review from checkpoint', exact: true }).click();
  await page.getByRole('button', { name: 'Retain hold', exact: true }).click();
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await expect(guide.getByRole('heading', { name: 'Outcomes follow your decisions.' })).toBeVisible();
  await expect(guide.getByText('still held', { exact: true })).toBeVisible();
  await expect(page).toHaveURL(/\/network$/);
  await guide.getByRole('button', { name: 'Finish and explore', exact: true }).click();
  await expect(guide).not.toBeVisible();
  await expect(page).toHaveURL(/\/network$/);
});

test('opening and cancelling a completed review preserves prior decisions', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/network');
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.getByRole('button', { name: /Take the journey|Follow one device|Start walkthrough/ }).click();
  const guide = page.getByRole('region', { name: 'One-device walkthrough' });
  await guide.getByRole('button', { name: 'Submit sample request', exact: true }).click();
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await guide.getByRole('button', { name: 'Review and choose', exact: true }).click();
  await page.getByRole('button', { name: 'Review from checkpoint', exact: true }).click();
  await page.getByRole('button', { name: 'Approve release', exact: true }).click();
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeEnabled();
  await guide.getByRole('button', { name: 'Review decision again', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeEnabled();
  await expect(guide.getByText('Decision recorded. Continue or review it again.')).toBeVisible();
  await guide.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(guide.getByText('Sample request submitted')).toBeVisible();
  await guide.getByRole('button', { name: 'Next step', exact: true }).click();
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeEnabled();
  await guide.getByRole('button', { name: 'End guided journey', exact: true }).click();
  await page.getByRole('button', { name: /Take the journey|Follow one device|Start walkthrough/ }).click();
  await expect(guide.getByRole('heading', { name: 'Start with one device.' })).toBeVisible();
  await expect(guide.getByRole('button', { name: 'Next step', exact: true })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});
